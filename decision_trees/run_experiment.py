"""Main entry point: generate data, learn ID3, evaluate, and save results."""

import argparse
from importlib.metadata import version
from itertools import product
import json
from pathlib import Path

import numpy as np
import pandas as pd

from .tree import build_tree, entropy, information_gain, predict, tree_to_text

SEED = 42
TARGET = "label"
DEFAULT_OUTPUT = Path(__file__).resolve().parent / "results"


def make_demo_data():
    """Generate 144 unique combinations using an explicitly invented rule.

    The labels are a teaching example, not measured human preferences.
    No external dataset or download is needed.
    """
    categories = {
        "weather": ["sunny", "cloudy", "rainy"],
        "wind": ["calm", "strong"],
        "temperature": ["cool", "mild", "warm"],
        "company": ["solo", "group"],
        "day_type": ["weekday", "weekend"],
        "time_of_day": ["morning", "evening"],
    }
    data = pd.DataFrame(product(*categories.values()), columns=list(categories))
    go_for_walk = (data.weather == "cloudy") | ((data.weather == "sunny") & (data.wind == "calm"))
    data[TARGET] = np.where(go_for_walk, "walk", "indoor")
    return data


def run_experiment():
    """Compare full ID3, a one-split tree, and the training-majority baseline."""
    # 1. Generate and split the data before fitting any tree.
    data = make_demo_data()
    order = np.random.default_rng(SEED).permutation(len(data))
    split = int(0.75 * len(data))
    train, test = data.iloc[order[:split]].copy(), data.iloc[order[split:]].copy()
    features = [name for name in data.columns if name != TARGET]

    # 2. Learn only from the training rows. Depth settings are fixed in advance.
    trees = {
        "ID3": build_tree(train),
        "One-split tree": build_tree(train, max_depth=1),
        "Majority baseline": build_tree(train, max_depth=0),
    }
    gains = pd.DataFrame({
        "feature": features,
        "information_gain_bits": [information_gain(train, name) for name in features],
    })

    # 3. Predict and compare accuracy using the same held-out rows.
    predictions = pd.DataFrame({"row_id": test.index, "actual": test[TARGET].to_numpy()})
    scores = []
    for name, tree in trees.items():
        train_predictions = np.asarray(predict(tree, train[features]))
        test_predictions = np.asarray(predict(tree, test[features]))
        predictions[name] = test_predictions
        scores.append({
            "method": name,
            "train_accuracy": float(np.mean(train_predictions == train[TARGET].to_numpy())),
            "test_accuracy": float(np.mean(test_predictions == test[TARGET].to_numpy())),
        })
    metadata = {
        "dataset": "Synthetic categorical activity example generated by make_demo_data",
        "label_rule": "walk if weather is cloudy, or weather is sunny and wind is calm; otherwise indoor",
        "seed": SEED, "n_train": len(train), "n_test": len(test),
        "training_entropy_bits": entropy(train[TARGET]),
        "root_feature": trees["ID3"]["feature"],
        "train_row_ids": train.index.tolist(), "test_row_ids": test.index.tolist(),
        "maximum_depth": {"ID3": None, "One-split tree": 1, "Majority baseline": 0},
        "packages": {name: version(name) for name in ("numpy", "pandas", "matplotlib")},
    }
    return {"train": train, "test": test, "tree": trees["ID3"], "gains": gains,
            "metrics": pd.DataFrame(scores), "predictions": predictions, "metadata": metadata}


def save_results(result, output=DEFAULT_OUTPUT):
    """Write seven compact artifacts, shared by the CLI and notebook."""
    import matplotlib.pyplot as plt
    from .plotting import plot_tree, plot_confusion_matrix

    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    result["metrics"].to_csv(output / "metrics.csv", index=False)
    result["gains"].to_csv(output / "information_gain.csv", index=False)
    result["predictions"].to_csv(output / "predictions.csv", index=False)
    (output / "tree.txt").write_text(tree_to_text(result["tree"]) + "\n")
    (output / "metadata.json").write_text(json.dumps(result["metadata"], indent=2) + "\n")
    for name, figure in [("tree", plot_tree(result["tree"])),
                         ("confusion_matrix", plot_confusion_matrix(result["predictions"]))]:
        figure.savefig(output / f"{name}.png", dpi=150)
        plt.close(figure)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    import matplotlib
    matplotlib.use("Agg")

    result = run_experiment()
    save_results(result, args.output)
    print(result["metrics"].round(4).to_string(index=False))
    print("\n" + tree_to_text(result["tree"]))
    print(f"\nSaved seven result files to {args.output}")


if __name__ == "__main__":
    main()
